/// 字段级覆盖动作。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum FieldAction {
    /// 强制该字段反序列化为指定 Rust 类型。
    /// 用于内联声明的类型（schema 中无法命名的 union/tuple 等）——
    /// 在 metatorio-data 手写具名类型（实现 Deserialize）后在此指定。
    Type(&'static str),
    /// 完全跳过该字段（不生成、不反序列化）。
    Skip,
}

/// 字段级覆盖规则：优先于类型级映射与忽略集。
///
/// `struct_name` 用 **schema 类型名**（如 `"CraftingMachinePrototype"`、
/// `"RecipePrototype"`），`field_name` 用 schema 字段名。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FieldRule {
    pub struct_name: &'static str,
    pub field_name: &'static str,
    pub action: FieldAction,
}

/// 生成配置。
#[derive(Debug, Clone)]
pub struct Config {
    /// 关注的原型类型（dump 顶层键名）。
    pub concerned_typenames: Vec<String>,
    /// 忽略的复合类型名。
    pub ignored_types: Vec<String>,
    /// schema 类型名 → 自定义 Rust 类型名（生成时直接使用该类型）。
    /// 例如 "Energy" → "metatorio_data::energy::EnergyAmount"
    pub custom_type_map: Vec<(String, String)>,
    /// 字段级覆盖规则（优先于类型级映射与忽略集）。
    pub field_rules: Vec<FieldRule>,
    /// 组合字段组：当多个原型链层同时声明整组字段且类型一致时，
    /// 提取为独立 Component（如 IconComponent），命中层的对应字段
    /// 替换为 `#[serde(flatten)]`（保持 dump 平铺解析，语义层可统一访问）。
    pub composite_field_groups: Vec<(String, Vec<String>)>,
    /// 提取阈值：同时声明该字段组的层数 ≥ 此值才提取。
    pub composite_min_layers: usize,
}

macro_rules! map_type {
    ($from:expr, $to:expr) => {
        (String::from($from), String::from($to))
    };
}

